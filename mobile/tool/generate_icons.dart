// Regenerates every static icon asset from the mark in
// lib/widgets/ironpeak_logo.dart and the variants in
// lib/theme/launcher_icons.dart, so they all come from one source:
//
//   * Android: one adaptive icon per LauncherIcons variant (backdrop color +
//     glyph foreground + the shared themed/monochrome layer), the
//     release-only launcher aliases that switch between them
//     (src/release/AndroidManifest.xml), the animated launch icon (light and
//     night), and the legacy mipmap PNGs
//   * web: favicon + PWA icons
//   * Windows: runner/resources/app_icon.ico
//   * iOS / macOS: the PNGs inside tool/branding/{ios,macos}/AppIcon.appiconset
//     (their Contents.json is hand-written; CI copies the folders into the
//     projects it generates with `flutter create`)
//   * tool/branding/ironpeak_icon_1024.png -- full-bleed master
//
// Run from mobile/ (it needs the Flutter engine for dart:ui, hence
// `flutter test`, not `dart run`; it lives in tool/ so a plain
// `flutter test` never rewrites resources):
//
//   flutter test tool/generate_icons.dart
//
// Optional env vars:
//   IRONPEAK_PREVIEW_DIR=<dir>   also write contact sheets of the variants
//                                and the motion
//   IRONPEAK_SKIP_ASSETS=1       preview only, leave the project untouched
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';
import 'dart:ui' as ui;

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:ironpeak_mobile/theme/launcher_icons.dart';
import 'package:ironpeak_mobile/widgets/ironpeak_logo.dart';

const String _res = 'android/app/src/main/res';

void main() {
  testWidgets('generate icon assets', (tester) async {
    await tester.runAsync(() async {
      final preview = Platform.environment['IRONPEAK_PREVIEW_DIR'];
      if (preview != null && preview.isNotEmpty) {
        await _writePreview(Directory(preview));
      }
      if (Platform.environment['IRONPEAK_SKIP_ASSETS'] == '1') return;

      await _writeAndroid();
      await _writeWeb();
      await _writeWindows();
      await _writeApple();
    });
  });
}

// --- rendering ---------------------------------------------------------

LauncherIconVariant get _default => LauncherIcons.defaultVariant;

Future<ui.Image> _render(
  int px, {
  LauncherIconVariant? variant,
  LogoShape shape = LogoShape.roundedSquare,
  LogoPose pose = LogoPose.rest,
  double glyph = IronpeakMark.badgeGlyphFraction,
  Color? background,
  Color? glyphColor,
}) {
  final v = variant ?? _default;
  final recorder = ui.PictureRecorder();
  final canvas = Canvas(recorder);
  IronpeakMark.paint(
    canvas,
    Size.square(px.toDouble()),
    shape: shape,
    pose: pose,
    glyphFraction: glyph,
    background: background ?? v.background,
    glyph: glyphColor ?? v.glyph,
  );
  return recorder.endRecording().toImage(px, px);
}

Future<Uint8List> _encode(ui.Image image) async {
  final data = await image.toByteData(format: ui.ImageByteFormat.png);
  return data!.buffer.asUint8List();
}

Future<Uint8List> _png(
  int px, {
  LauncherIconVariant? variant,
  LogoShape shape = LogoShape.roundedSquare,
  double glyph = IronpeakMark.badgeGlyphFraction,
  Color? background,
  Color? glyphColor,
}) async {
  return _encode(await _render(
    px,
    variant: variant,
    shape: shape,
    glyph: glyph,
    background: background,
    glyphColor: glyphColor,
  ));
}

Future<void> _write(String path, List<int> bytes) async {
  final file = File(path);
  await file.parent.create(recursive: true);
  await file.writeAsBytes(bytes);
  stdout.writeln('wrote $path (${bytes.length} bytes)');
}

Future<void> _writeText(String path, String text) {
  for (final comment in RegExp(r'<!--(.*?)-->', dotAll: true).allMatches(text)) {
    if (comment.group(1)!.contains('--')) {
      throw StateError('$path: a "--" inside an XML comment is not well-formed');
    }
  }
  return _write(path, utf8.encode(text));
}

// --- Android -------------------------------------------------------------

// XML comments may not contain a double hyphen (aapt2: "not well-formed"),
// so no `--` dashes in any comment text below.
const String _generated =
    '<!-- GENERATED by tool/generate_icons.dart from '
    'lib/widgets/ironpeak_logo.dart and lib/theme/launcher_icons.dart. Edit '
    'the Dart, then re-run `flutter test tool/generate_icons.dart`. -->';

String _hex(Color c) =>
    '#${c.toARGB32().toRadixString(16).padLeft(8, '0').toUpperCase()}';

String _num(double v) {
  var s = v.toStringAsFixed(3);
  s = s.replaceFirst(RegExp(r'0+$'), '').replaceFirst(RegExp(r'\.$'), '');
  return s == '-0' ? '0' : s;
}

String _backdropColorName(IconBackdrop b) => 'ic_launcher_backdrop_${b.name}';

String _foregroundName(LauncherIconVariant v) => 'ic_launcher_foreground_${v.id}';

// 108dp canvas, glyph box = the 66dp safe zone: unit -> x0.66, +21.
String _glyphGroup(String body, {required int indent}) {
  final p = ' ' * indent;
  return '$p<group\n'
      '$p    android:scaleX="0.66"\n'
      '$p    android:scaleY="0.66"\n'
      '$p    android:translateX="21"\n'
      '$p    android:translateY="21">\n'
      '$body\n'
      '$p</group>';
}

String _path(String data, Color color, {required int indent, double alpha = 1}) {
  final p = ' ' * indent;
  return '$p<path\n'
      '$p    android:fillColor="${_hex(color)}"\n'
      '${alpha == 1 ? '' : '$p    android:fillAlpha="${_num(alpha)}"\n'}'
      '$p    android:pathData="$data" />';
}

/// The static glyph (resting pose) as a 108dp vector: what every launcher
/// foreground and the monochrome layer are made of.
String _glyphVector(Color color) {
  final paths = [
    _path(IronpeakMark.peak, color, indent: 8),
    _path(IronpeakMark.bar, color, indent: 8),
    _path(IronpeakMark.plates, color, indent: 8),
  ].join('\n');
  return '''<?xml version="1.0" encoding="utf-8"?>
$_generated
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
${_glyphGroup(paths, indent: 4)}
</vector>
''';
}

String _adaptiveIcon(LauncherIconVariant v) => '''<?xml version="1.0" encoding="utf-8"?>
$_generated
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/${_backdropColorName(v.backdrop)}" />
    <foreground android:drawable="@drawable/${_foregroundName(v)}" />
    <!-- Android 13+ themed icons: the system tints this layer instead. -->
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''';

Future<void> _writeAndroid() async {
  // Legacy launchers (API < 26 never ships: minSdk is 26) -- but nothing in
  // the app should still show an old mark.
  const sizes = {
    'mdpi': 48,
    'hdpi': 72,
    'xhdpi': 96,
    'xxhdpi': 144,
    'xxxhdpi': 192,
  };
  for (final e in sizes.entries) {
    await _write('$_res/mipmap-${e.key}/ic_launcher.png', await _png(e.value));
  }

  final colors = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln(_generated)
    ..writeln('<resources>');
  for (final b in IconBackdrop.values) {
    final c = b == IconBackdrop.dark ? LauncherIcons.darkBackdrop : LauncherIcons.lightBackdrop;
    colors.writeln('    <color name="${_backdropColorName(b)}">${_hex(c)}</color>');
  }
  colors.writeln('</resources>');
  await _writeText('$_res/values/ic_launcher_backdrops.xml', colors.toString());

  for (final v in LauncherIcons.all) {
    await _writeText('$_res/drawable/${_foregroundName(v)}.xml', _glyphVector(v.glyph));
    await _writeText('$_res/mipmap-anydpi-v26/${v.androidIcon}.xml', _adaptiveIcon(v));
  }
  // The application's own icon (what debug builds and the system's app
  // info show) is the default variant.
  await _writeText('$_res/mipmap-anydpi-v26/ic_launcher.xml', _adaptiveIcon(_default));
  await _writeText('$_res/drawable/ic_launcher_monochrome.xml', _glyphVector(const Color(0xFF000000)));

  await _writeText('$_res/drawable/ic_splash_animated.xml',
      _splashAnimatedVector(LauncherIconVariant(IconBackdrop.light, _default.hue).glyph));
  await _writeText('$_res/drawable-night/ic_splash_animated.xml',
      _splashAnimatedVector(LauncherIconVariant(IconBackdrop.dark, _default.hue).glyph));

  await _writeText('android/app/src/release/AndroidManifest.xml', _releaseManifest());
}

/// Release builds only: hides the real activity's own launcher entry and
/// declares one launcher alias per icon variant, exactly one enabled. The
/// app enables/disables them at runtime (IronpeakActivity.kt) to follow its
/// appearance. Debug and profile builds keep the plain launcher activity,
/// because `flutter run` only ever launches an <activity>, never an alias.
String _releaseManifest() {
  final aliases = StringBuffer();
  for (final v in LauncherIcons.all) {
    final isDefault = v == _default;
    aliases.writeln('''        <activity-alias
            android:name="${v.androidAlias}"
            android:enabled="$isDefault"
            android:exported="true"
            android:icon="@mipmap/${v.androidIcon}"
            android:targetActivity="${LauncherIcons.androidActivity}">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>''');
  }
  return '''<?xml version="1.0" encoding="utf-8"?>
$_generated
<!-- Release builds only (manifest merger overlay on src/main): one launcher
     alias per icon variant in lib/theme/launcher_icons.dart, all targeting
     the real Flutter activity, whose own launcher filter is removed here.
     Exactly one alias is enabled; IronpeakActivity.kt switches them after the
     user leaves the app. Aliases may be added but NEVER removed or renamed:
     a phone whose enabled alias disappears in an update has no launcher
     entry left. The default variant keeps the component name the launcher
     activity had before aliases existed (.MainActivity), so home screen
     shortcuts made by older versions keep working. Debug and profile builds
     have no aliases: flutter run only launches a real activity. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools">
    <application>
        <activity android:name="${LauncherIcons.androidActivity}">
            <intent-filter tools:node="removeAll" />
        </activity>
${aliases.toString().trimRight()}
    </application>
</manifest>
''';
}

int _ms(double seconds) => (seconds * 1000).round();

String _animator(
  String target,
  String property,
  num from,
  num to, {
  required (double, double) timing,
  required String interpolator,
}) {
  final (start, seconds) = timing;
  return '''    <target android:name="$target">
        <aapt:attr name="android:animation">
            <objectAnimator
                android:propertyName="$property"
                android:valueFrom="$from"
                android:valueTo="$to"
                android:valueType="floatType"
                android:duration="${_ms(seconds)}"
${start == 0 ? '' : '                android:startOffset="${_ms(start)}"\n'}                android:interpolator="$interpolator" />
        </aapt:attr>
    </target>''';
}

/// The Android 12+ launch icon: the same shapes as the launcher icon, but
/// every moving part starts in its t=0 pose (bar and plates collapsed,
/// summit behind the bar) and is animated to rest, so a delayed animator
/// never flashes the finished mark first. The script mirrors
/// IronpeakMark.poseAt's intro, number for number, with Android's own
/// interpolators (the Dart side implements the same curves).
String _splashAnimatedVector(Color color) {
  final cx = _num(50);
  final cy = _num(IronpeakMark.barCenterY);
  final targets = [
    _animator('bar', 'scaleX', 0, 1,
        timing: IronpeakMark.barGrow,
        interpolator: '@android:interpolator/fast_out_slow_in'),
    _animator('plates', 'scaleY', 0, 1,
        timing: IronpeakMark.platesSnap,
        interpolator: '@android:anim/overshoot_interpolator'),
    _animator('peak', 'translateY', IronpeakMark.peakRise, 0,
        timing: IronpeakMark.peakRiseTiming,
        interpolator: '@android:interpolator/fast_out_slow_in'),
  ].join('\n');
  final horizon = _num(IronpeakMark.horizonY);
  final body = '''                <group android:name="horizon">
                    <clip-path android:pathData="M-100,-100H200V${horizon}H-100Z" />
                    <group
                        android:name="peak"
                        android:translateY="${_num(IronpeakMark.peakRise)}">
${_path(IronpeakMark.peak, color, indent: 24)}
                    </group>
                </group>
                <group
                    android:name="bar"
                    android:pivotX="$cx"
                    android:pivotY="$cy"
                    android:scaleX="0">
${_path(IronpeakMark.bar, color, indent: 20)}
                </group>
                <group
                    android:name="plates"
                    android:pivotX="$cx"
                    android:pivotY="$cy"
                    android:scaleY="0">
${_path(IronpeakMark.plates, color, indent: 20)}
                </group>''';
  return '''<?xml version="1.0" encoding="utf-8"?>
$_generated
<!-- Played once by the Android 12+ system splash screen
     (windowSplashScreenAnimatedIcon, see values*-v31/styles.xml) on the
     app background color: the bar grows out from its center, the plates
     snap open, the summit rises from behind the bar. The glyph sits in the
     66 unit safe zone of the 108 unit canvas, inside the circle the splash
     screen masks its icon to. Total length stays under the 1000ms limit.
     drawable-night holds the dark mode copy (lighter glyph color). -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt">
    <aapt:attr name="android:drawable">
        <vector
            android:width="108dp"
            android:height="108dp"
            android:viewportWidth="108"
            android:viewportHeight="108">
${_glyphGroup(body, indent: 12)}
        </vector>
    </aapt:attr>
$targets
</animated-vector>
''';
}

// --- web -------------------------------------------------------------------

Future<void> _writeWeb() async {
  await _write('web/favicon.png', await _png(32));
  // Full-bleed squares: the platform masks them (iOS touch icon, maskable
  // PWA icons), and the glyph stays inside the maskable safe zone (80%).
  for (final px in [192, 512]) {
    final bytes = await _png(px,
        shape: LogoShape.square, glyph: IronpeakMark.launcherGlyphFraction);
    await _write('web/icons/Icon-$px.png', bytes);
    await _write('web/icons/Icon-maskable-$px.png', bytes);
  }
}

// --- Windows .ico -----------------------------------------------------------

Future<void> _writeWindows() async {
  // Classic layout: DIB entries for the small sizes (what every shell
  // version understands), PNG for 256.
  const dibSizes = [16, 24, 32, 48, 64];
  final entries = <_IcoEntry>[];
  for (final px in dibSizes) {
    final image = await _render(px);
    final rgba = (await image.toByteData(format: ui.ImageByteFormat.rawStraightRgba))!
        .buffer
        .asUint8List();
    entries.add(_IcoEntry(px, _dib(px, rgba)));
  }
  entries.add(_IcoEntry(256, await _png(256)));
  await _write('windows/runner/resources/app_icon.ico', _ico(entries));
}

class _IcoEntry {
  _IcoEntry(this.size, this.data);
  final int size;
  final Uint8List data;
}

/// BITMAPINFOHEADER + bottom-up BGRA pixels + a (blank) 1-bit AND mask --
/// the alpha channel carries the transparency.
Uint8List _dib(int px, Uint8List rgba) {
  final maskRow = ((px + 31) ~/ 32) * 4;
  final maskBytes = maskRow * px;
  final out = BytesBuilder();
  final header = ByteData(40)
    ..setUint32(0, 40, Endian.little)
    ..setInt32(4, px, Endian.little)
    ..setInt32(8, px * 2, Endian.little) // XOR + AND mask heights
    ..setUint16(12, 1, Endian.little)
    ..setUint16(14, 32, Endian.little)
    ..setUint32(20, px * px * 4 + maskBytes, Endian.little);
  out.add(header.buffer.asUint8List());
  for (var y = px - 1; y >= 0; y--) {
    for (var x = 0; x < px; x++) {
      final i = (y * px + x) * 4;
      out.add([rgba[i + 2], rgba[i + 1], rgba[i], rgba[i + 3]]);
    }
  }
  out.add(Uint8List(maskBytes));
  return out.toBytes();
}

Uint8List _ico(List<_IcoEntry> entries) {
  final out = BytesBuilder();
  final dir = ByteData(6 + 16 * entries.length)
    ..setUint16(2, 1, Endian.little) // type: icon
    ..setUint16(4, entries.length, Endian.little);
  var offset = dir.lengthInBytes;
  for (var i = 0; i < entries.length; i++) {
    final e = entries[i];
    final o = 6 + 16 * i;
    dir
      ..setUint8(o, e.size >= 256 ? 0 : e.size)
      ..setUint8(o + 1, e.size >= 256 ? 0 : e.size)
      ..setUint16(o + 4, 1, Endian.little)
      ..setUint16(o + 6, 32, Endian.little)
      ..setUint32(o + 8, e.data.length, Endian.little)
      ..setUint32(o + 12, offset, Endian.little);
    offset += e.data.length;
  }
  out.add(dir.buffer.asUint8List());
  for (final e in entries) {
    out.add(e.data);
  }
  return out.toBytes();
}

