const String _ios = 'tool/branding/ios/AppIcon.appiconset';
const String _macos = 'tool/branding/macos/AppIcon.appiconset';

Future<void> _writeApple() async {
  // iOS masks a full-bleed opaque square itself. The light variant is the
  // icon; iOS 18 adds the home screen's dark and tinted appearances.
  final master = await _png(1024, shape: LogoShape.square);
  await _write('tool/branding/ironpeak_icon_1024.png', master);
  await _write('$_ios/AppIcon-1024.png', master);
  await _write(
    '$_ios/AppIcon-1024-dark.png',
    await _png(1024,
        shape: LogoShape.square,
        variant: LauncherIconVariant(IconBackdrop.dark, _default.hue)),
  );
  // Tinted: the system desaturates the image and tints it by luminance, so
  // a white glyph on black comes out as the user's tint on dark.
  await _write(
    '$_ios/AppIcon-1024-tinted.png',
    await _png(1024,
        shape: LogoShape.square,
        background: const Color(0xFF000000),
        glyphColor: const Color(0xFFFFFFFF)),
  );

  // macOS does not mask: the PNG itself carries the rounded body, inset on
  // the canvas like Apple's own icons (824 of 1024, corner radius ~22.5%).
  for (final px in [16, 32, 64, 128, 256, 512, 1024]) {
    await _write('$_macos/app_icon_$px.png', await _macIcon(px));
  }
}

Future<Uint8List> _macIcon(int px) async {
  final recorder = ui.PictureRecorder();
  final canvas = Canvas(recorder);
  final s = px / 1024;
  final body = Rect.fromLTWH(100 * s, 100 * s, 824 * s, 824 * s);
  final rrect = RRect.fromRectAndRadius(body, Radius.circular(185 * s));
  if (px >= 64) {
    // The soft drop shadow every macOS app icon has; invisible below 64px.
    canvas.drawRRect(
      rrect.shift(Offset(0, 10 * s)),
      Paint()
        ..color = const Color(0x4D000000)
        ..maskFilter = MaskFilter.blur(BlurStyle.normal, 12 * s),
    );
  }
  canvas.save();
  canvas.clipRRect(rrect);
  canvas.translate(body.left, body.top);
  IronpeakMark.paint(
    canvas,
    body.size,
    shape: LogoShape.square,
    background: _default.background,
    glyph: _default.glyph,
  );
  canvas.restore();
  return _encode(await recorder.endRecording().toImage(px, px));
}

// --- preview sheets -------------------------------------------------------------

/// Contact sheets to eyeball the design and the motion without a device:
/// every launcher variant under a few launcher masks, the themed layer, the
/// intro and loop frames, and real-size legibility.
Future<void> _writePreview(Directory dir) async {
  await dir.create(recursive: true);
  const cell = 120.0;
  const pad = 12.0;
  const cols = 8;

  Future<void> save(String name, int w, int h, void Function(Canvas) draw) async {
    final recorder = ui.PictureRecorder();
    draw(Canvas(recorder));
    final image = await recorder.endRecording().toImage(w, h);
    await File('${dir.path}/$name').writeAsBytes(await _encode(image));
    stdout.writeln('preview: ${dir.path}/$name');
  }

  void tile(Canvas c, double x, double y, double size, void Function(Canvas) body, {double radius = 0.5}) {
    c.save();
    c.translate(x, y);
    c.clipRRect(RRect.fromRectAndRadius(Offset.zero & Size.square(size), Radius.circular(size * radius)));
    // Show the masked 72dp of the 108dp adaptive canvas.
    c.translate(-size * 18 / 72, -size * 18 / 72);
    body(c);
    c.restore();
  }

  // Variants: one row per backdrop, circle masks, then squircle masks.
  const vw = pad + cols * (cell + pad);
  const vh = pad + 5 * (cell + pad);
  await save('variants.png', vw.toInt(), vh.toInt(), (c) {
    c.drawRect(const Rect.fromLTWH(0, 0, vw, vh), Paint()..color = const Color(0xFFDADCE2));
    final all = LauncherIcons.all;
    for (var i = 0; i < all.length; i++) {
      final v = all[i];
      final x = pad + (i % cols) * (cell + pad);
      for (final (row, radius) in [(i ~/ cols, 0.5), (2 + i ~/ cols, 0.3)]) {
        tile(c, x, pad + row * (cell + pad), cell, (c) {
          IronpeakMark.paint(c, const Size.square(cell * 108 / 72),
              shape: LogoShape.square,
              background: v.background,
              glyph: v.glyph,
              glyphFraction: IronpeakMark.launcherGlyphFraction);
        }, radius: radius);
      }
    }
    // Themed (monochrome) icons as Android 13+ tints them.
    const themed = [
      (Color(0xFFDCE4F9), Color(0xFF2A3C5F)),
      (Color(0xFF2E3B4E), Color(0xFFCFDDF9)),
      (Color(0xFFE7F0D9), Color(0xFF2F4A1B)),
    ];
    for (var i = 0; i < themed.length; i++) {
      final (bg, fg) = themed[i];
      tile(c, pad + i * (cell + pad), pad + 4 * (cell + pad), cell, (c) {
        IronpeakMark.paint(c, const Size.square(cell * 108 / 72),
            shape: LogoShape.square,
            background: bg,
            glyph: fg,
            glyphFraction: IronpeakMark.launcherGlyphFraction);
      });
    }
    // Real-size legibility: 24 / 32 / 48 dp equivalents.
    var x = pad + 3 * (cell + pad);
    for (final px in [24.0, 32.0, 48.0, 72.0]) {
      for (final (j, v) in [_default, LauncherIconVariant(IconBackdrop.dark, _default.hue)].indexed) {
        tile(c, x, pad + 4 * (cell + pad) + j * 60, px, (c) {
          IronpeakMark.paint(c, Size.square(px * 108 / 72),
              shape: LogoShape.square,
              background: v.background,
              glyph: v.glyph,
              glyphFraction: IronpeakMark.launcherGlyphFraction);
        });
      }
      x += px + pad;
    }
  });

  // Motion: intro every 100 ms, then the loop.
  final intro = [for (var ms = 0; ms <= 900; ms += 100) ms / 1000];
  final loop = [0.0, 1.2, 1.5, 1.7, 1.9, 2.1, 2.4, 2.7, 2.9, 3.4]
      .map((u) => IronpeakMark.introSeconds + u)
      .toList();
  const mw = pad + 10 * (cell + pad);
  const mh = pad + 4 * (cell + pad);
  await save('motion.png', mw.toInt(), mh.toInt(), (c) {
    c.drawRect(const Rect.fromLTWH(0, 0, mw, mh), Paint()..color = const Color(0xFFDADCE2));
    for (final (row, times) in [(0, intro), (2, loop)]) {
      for (var i = 0; i < times.length; i++) {
        for (final (dy, v) in [_default, LauncherIconVariant(IconBackdrop.dark, _default.hue)].indexed) {
          c.save();
          c.translate(pad + i * (cell + pad), pad + (row + dy) * (cell + pad));
          IronpeakMark.paint(c, const Size.square(cell),
              pose: IronpeakMark.poseAt(times[i]),
              background: v.background,
              glyph: v.glyph);
          c.restore();
        }
      }
    }
  });
